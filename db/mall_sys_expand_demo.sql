-- 17.0 广告位候选池说明：所有新广告都从 tmp_new_sku 里挑真实商品，
--      图片走 /PublishGoods/showImg/goods/{main_img}，点击跳到 /goods/{spuId}?sku={skuCode}。
INSERT INTO tbl_advertisement(id,ad_name,placement,image_url,target_url,weight,start_time,end_time,status,created_at)
SELECT 6 + ROW_NUMBER() OVER (ORDER BY t.spu_id), t.goods_name, t.placement, t.image_url,
       t.target_url, t.weight, t.start_time, t.end_time, t.status, t.created_at
FROM (
  SELECT k.spu_id, CONCAT(s.goods_name,' 推广位') AS goods_name,
         CASE MOD(k.spu_id,4) WHEN 0 THEN '首页轮播' WHEN 1 THEN '频道横幅'
                              WHEN 2 THEN '搜索推荐' ELSE '首页轮播' END AS placement,
         CONCAT('/PublishGoods/showImg/goods/',s.main_img) AS image_url,
         CONCAT('/goods/',s.id,'?sku=',k.sku_code) AS target_url,
         70 + MOD(k.spu_id,40) AS weight,
         '2026-06-01 00:00:00' AS start_time,
         CASE WHEN MOD(k.spu_id,3) = 0 THEN '2026-08-31 23:59:59' ELSE '2026-10-31 23:59:59' END AS end_time,
         CASE WHEN MOD(k.spu_id,3) = 0 THEN '已下架' ELSE '已上架' END AS status,
         '2026-05-25 14:00:00' AS created_at
  FROM (
    -- 每个 SPU 只取一个代表 SKU（sku_id 最小的那个）挂广告
    SELECT k2.spu_id, MIN(k2.sku_id) AS sku_id, MIN(k2.sku_code) AS sku_code
      FROM tmp_new_sku k2 GROUP BY k2.spu_id
  ) k
  JOIN tbl_spu_detail s ON s.id = k.spu_id
  WHERE MOD(k.spu_id,10) = 0 OR MOD(k.spu_id,17) = 0 OR k.spu_id IN (10013,10015,10024,10029,10034,10046)
  -- 按 spu_id 取模排序而不是顺序取前 6 个：让第一批商品和第二批（家电/影音/外设）
  -- 都有机会上位，避免广告位被 id 最小的一批商品占满
  ORDER BY MOD(k.spu_id,7), k.spu_id
  LIMIT 6
) t;

