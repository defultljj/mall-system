-- =============================================================================
-- mall_sys_expand_demo.sql
-- 演示数据扩充脚本：把 mall_sys 从「每张表十来行的小样本」扩到「讲得清经营分析的规模」。
--
-- 前置条件（本脚本是增量脚本，不重建全库）：
--   先跑过 db/mall_sys_full_demo.sql，库里已存在 18 类目 / 11 品牌 / 12 SPU / 24 SKU
--   / 24 会员 / 30 订单。
--
-- 目标规模：类目 44、品牌 49、SPU 85、SKU ~234、库存与 SKU 一一对应、
--          会员 ~100、订单 ~300、行为 ~1000、评价 ~200、客服会话 ~100。
--
-- 新增商品的图片与品牌 logo 全部来自 db/image_manifest.tsv（111 行：73 商品 + 38 品牌），
-- 文件已落在 upload/goods 与 upload/brand 下，脚本只引用文件名，不改动任何图片。
--
-- 幂等做法（可重复执行，结果一致）：
--   脚本开头先删掉「上一次自己插进去的数据」，再重新插入（先删引用方，再删被引用方）。
--   删除范围的判定依据（第 1 节逐条对应）刻意不写成裸的自增 id 区间，而是取
--   脚本自己写死的数据特征，免得后台新增的会员 / 商品 / 订单正好撞上这些区间被误删：
--     积分流水        member_id 指向本脚本会员
--     客服会话/评价   挂在 order_id LIKE 'O2026%' AND order_time < '2026-09-01' 的订单上
--     行为日志        (session_id = 'SESS-'+新订单号 OR 'SESS-BROWSE-%') AND log_id 在 500000~899999
--     订单            order_id LIKE 'O2026%' AND order_time < '2026-09-01'
--                     （现有 30 单全部是 2026-09-01 之后，后台新下的单也是当天时间）
--     库存流水        flow_no 以 INIT-/SALE-/RETURN- 开头，且挂在脚本自建库存上
--     SKU 销售属性值  sku_id 指向脚本自建 SKU
--     SKU / 库存      sku_code REGEXP '^SKU-[0-9]{4}-'（第 7 节命名：SKU+4 位序号+规格+颜色）
--                     且 id 在 300001~309999；后台新建 SKU 的编码是 SKU-%06d，不匹配
--     商品属性值      spu_id 在 10013~10085（spu_id IS NULL 的可选值字典行走 INSERT 的 NOT EXISTS 去重）
--     SPU             id 在 10013~10085（基础数据 1~12；脚本跑过之后后台新商品从 10086 起）
--     会员            id 在 25~100 AND user_id = 'U1'+4 位 id（第 9 节的生成规则）
--     活动/广告       id 在 7~22 / 7~12 AND created_at 等于脚本写死的创建时间
--                     （活动 2026-05-20~2026-09-10，广告统一 2026-05-25 14:00:00）
--     品牌/品牌类目   id 在 1012~1049 AND update_date = '2026-09-01 09:00:00'（第 3.1 节的固定值）
--     属性分组关系    attr_group_id IN (脚本新建的 14 个分组)
--     属性定义/分组   category_id IN (脚本新建的 14 个叶子类目)
--     类目            (id,parent_id) 精确配对（第 2 节那 26 个类目）
--   注意：现有数据的 id 段一律不动，脚本只做「删自己插过的 + 重新插入」。
--   副作用提示：若有人手工改过脚本写过的行（例如改了品牌名），该行可能不再匹配上述判据，
--   重跑会在 INSERT 处报主键冲突——此时按报错手工清理该行即可，脚本不会静默删用户数据。
--
-- 确定性：不使用 RAND()/UUID()，所有分配都走 MOD(id, n) / ELT(...) 取模，
--         同一份输入每次执行结果完全一致。
--
-- 用法：
--   mysql -uroot -p --default-character-set=utf8mb4 mall_sys < db/mall_sys_expand_demo.sql
--
-- 执行完请再跑一次 db/mall_sys_local_analysis_seed.sql 重建分析结果表。
-- =============================================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- =============================================================================
-- 1. 幂等清理：只删本脚本上一次插入的数据（引用方在前，被引用方在后）
-- =============================================================================

-- 1.1 挂在新会员上的积分流水
--     判据：member_id 指向本脚本生成的会员（第 9 节：id 25~100 且 user_id = 'U1'+4 位 id）
DELETE FROM tbl_points_flow
 WHERE member_id IN (
       SELECT id FROM tbl_member
        WHERE id BETWEEN 25 AND 100 AND user_id = CONCAT('U1', LPAD(id, 4, '0')));

-- 1.2 挂在新订单上的客服会话（session_id = 'CS-' + order_id）
DELETE FROM tbl_customer_service_session
 WHERE session_id IN (
       SELECT CONCAT('CS-', order_id) FROM tbl_sales_order
        WHERE order_id LIKE 'O2026%' AND order_time < '2026-09-01 00:00:00');

-- 1.3 挂在新订单上的评价（review_id = 'R' + order_id 去首字母）
DELETE FROM tbl_review
 WHERE order_id IN (
       SELECT order_id FROM tbl_sales_order
        WHERE order_id LIKE 'O2026%' AND order_time < '2026-09-01 00:00:00');

-- 1.4 新行为日志（第 11 节只写 'SESS-'+新订单号 与 'SESS-BROWSE-' 两种 session_id）
DELETE FROM tbl_behavior_event
 WHERE log_id BETWEEN 500000 AND 899999
   AND (session_id LIKE 'SESS-BROWSE-%'
        OR session_id IN (SELECT CONCAT('SESS-', order_id) FROM tbl_sales_order
                           WHERE order_id LIKE 'O2026%' AND order_time < '2026-09-01 00:00:00'));

-- 1.5 新订单
DELETE FROM tbl_sales_order
 WHERE order_id LIKE 'O2026%' AND order_time < '2026-09-01 00:00:00';

-- 1.6 新库存流水 / SKU 销售属性值 / 库存 / SKU
--     判据：sku_code 形如 SKU-<4 位序号>-<规格码>-<颜色码>（第 7 节命名规则，序号 = spu_id-10012）。
--     后台新建 SKU 的编码是 SKU-%06d（GoodsDetailServiceImpl），基础数据是 SKU-IP16-128-BLK 这种，
--     都不匹配该正则，不会被删。顺序上先删引用 SKU / 库存的行，再删库存、SKU 本身。
DELETE FROM tbl_inventory_flow
 WHERE flow_no REGEXP '^(INIT|SALE|RETURN)-'
   AND inventory_id IN (SELECT id FROM tbl_inventory
                         WHERE sku_code REGEXP '^SKU-[0-9]{4}-' AND id BETWEEN 300001 AND 309999);

DELETE FROM tbl_sku_sale_attr_value
 WHERE sku_id IN (SELECT id FROM tbl_sku
                   WHERE sku_code REGEXP '^SKU-[0-9]{4}-' AND id BETWEEN 300001 AND 309999);

DELETE FROM tbl_inventory
 WHERE sku_code REGEXP '^SKU-[0-9]{4}-' AND id BETWEEN 300001 AND 309999;

DELETE FROM tbl_sku
 WHERE sku_code REGEXP '^SKU-[0-9]{4}-' AND id BETWEEN 300001 AND 309999;

-- 1.7 商品属性值：只删挂在本脚本 SPU 上的规格参数行
--     spu_id IS NULL 的「属性可选值字典」行不在这里删：第 7.6 节的 INSERT 带 NOT EXISTS 去重，
--     重复执行不会多出重复行，同时避免误删后台维护的可选值。
DELETE FROM tbl_goods_attr_value
 WHERE spu_id BETWEEN 10013 AND 10085;

-- 1.8 新 SPU（判据：id 段。基础数据 1~12；本脚本跑过之后后台新商品从 10086 起，不会落进来）
DELETE FROM tbl_spu_detail
 WHERE id BETWEEN 10013 AND 10085;

-- 1.9 新会员（判据：id 段 + 第 9 节的 user_id 生成规则；后台注册的 user_id 由人工填写，不匹配）
DELETE FROM tbl_member
 WHERE id BETWEEN 25 AND 100 AND user_id = CONCAT('U1', LPAD(id, 4, '0'));

-- 1.10 新活动 / 新广告（判据：id 段 + 脚本写死的 created_at；
--      区间就是第 16 / 17 节 INSERT 里那几行 created_at 的最小 / 最大值，
--      后台新建的活动 / 广告 created_at 是当天时间，落在区间外，不会被删）
DELETE FROM tbl_advertisement
 WHERE id BETWEEN 7 AND 12 AND created_at = '2026-05-25 14:00:00';

DELETE FROM tbl_activity
 WHERE id BETWEEN 7 AND 22
   AND created_at BETWEEN '2026-05-20 10:00:00' AND '2026-09-10 15:00:00';

-- 1.11 新品牌及其类目关联（判据：id 段 + 第 3.1 节统一的 update_date 固定值）
DELETE FROM tbl_brand_category
 WHERE brand_id IN (SELECT id FROM tbl_brand
                     WHERE id BETWEEN 1012 AND 1049 AND update_date = '2026-09-01 09:00:00');

DELETE FROM tbl_brand
 WHERE id BETWEEN 1012 AND 1049 AND update_date = '2026-09-01 09:00:00';

-- 1.12 新类目的属性分组关系 / 属性定义 / 属性分组
--      分组关系按 attr_group_id 圈定（本脚本新建的 14 个分组），不再用裸 id 区间
DELETE FROM tbl_group_attr_relation
 WHERE attr_group_id IN (12201,13101,14101,14201,21201,21301,21401,22201,23101,12301,13301,15101,15201,15301);

DELETE FROM tbl_goods_attr
 WHERE category_id IN (122,123,131,133,141,142,151,152,153,212,213,214,222,231);

DELETE FROM tbl_goods_attr_group
 WHERE category_id IN (122,123,131,133,141,142,151,152,153,212,213,214,222,231);

-- 1.13 新类目（三层树，从叶子往上删）
--      判据：(id,parent_id) 精确配对 —— 只认第 2 节那 26 个类目。后台新建的类目即使自增 id
--      正好撞上（例如基础数据最大 id 是 421，下一个自增就是 422），parent_id 也对不上，不会被删。
