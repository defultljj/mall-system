DROP TEMPORARY TABLE IF EXISTS tmp_cat_tree;
CREATE TEMPORARY TABLE tmp_cat_tree (
  root INT, id INT, PRIMARY KEY (root, id)
) ENGINE=InnoDB;

INSERT INTO tmp_cat_tree
WITH RECURSIVE t(root,id) AS (
  SELECT c.id, c.id FROM tbl_goods_category c
  UNION ALL
  SELECT t.root, c2.id FROM t JOIN tbl_goods_category c2 ON c2.parent_id = t.id
)
SELECT root, id FROM t;

UPDATE tbl_goods_category c
SET c.product_count = (
  SELECT COUNT(*) FROM tbl_spu_detail p JOIN tmp_cat_tree t ON t.id = p.category_id
   WHERE t.root = c.id);

