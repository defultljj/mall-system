FROM tbl_behavior_event b LEFT JOIN tbl_member m ON m.user_id = b.user_id WHERE m.id IS NULL
UNION ALL SELECT 'unknown_behavior_sku', COUNT(*)
FROM tbl_behavior_event b LEFT JOIN tbl_inventory i ON i.sku_code = b.product_id WHERE i.id IS NULL
UNION ALL SELECT 'review_without_completed_order', COUNT(*)
FROM tbl_review r LEFT JOIN tbl_sales_order o ON o.order_id = r.order_id AND o.order_status = '已完成' WHERE o.order_id IS NULL
UNION ALL SELECT 'sku_inventory_stock_mismatch', COUNT(*)
FROM tbl_sku s JOIN tbl_inventory i ON i.sku_code = s.sku_code WHERE s.stock <> i.stock
UNION ALL SELECT 'member_spend_mismatch', COUNT(*)
FROM tbl_member m LEFT JOIN (SELECT user_id, ROUND(SUM(pay_amount - COALESCE(return_amount,0)),2) spent
                             FROM tbl_sales_order WHERE order_status='已完成' GROUP BY user_id) x
  ON x.user_id = m.user_id WHERE m.total_spent <> COALESCE(x.spent,0);

